#!/usr/bin/env python3
"""Regenerates the art index that the encyclopedia reads.

Scans assets/heroes, assets/skins, assets/sceneries and assets/equipment and
writes:
  assets/data/art-manifest.json   the full index (also lists icons/alternates)
  assets/js/art-data.js           window.PDX_ART, loaded by heroes.html

Run from the repository root after adding or renaming art:

    python3 tools/build-art-manifest.py

File naming (all lower-case, words joined with "-"):
  assets/heroes/<hero-id>.webp|png|jpg|svg
  assets/skins/<hero-id>-<skin-name>.webp|png|jpg|svg
  assets/sceneries/<scenery-name>.webp|png|jpg|svg
  assets/equipment/<equipment-name>.webp|png|jpg|svg

The six hero ids are barbarian-king, archer-queen, grand-warden,
royal-champion, minion-prince and dragon-duke.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXTS = (".webp", ".png", ".jpg", ".jpeg", ".svg")
HERO_IDS = (
    "barbarian-king", "archer-queen", "grand-warden",
    "royal-champion", "minion-prince", "dragon-duke",
)


def key_of(path):
    return os.path.splitext(os.path.basename(path))[0]


def rel(path):
    return "./" + os.path.relpath(path, ROOT).replace(os.sep, "/")


def scan(folder):
    """{key: './assets/<folder>/<file>'} — photos beat vector fallbacks."""
    out, base = {}, os.path.join(ROOT, "assets", folder)
    if not os.path.isdir(base):
        return out
    files = [n for n in sorted(os.listdir(base))
             if os.path.isfile(os.path.join(base, n)) and n.lower().endswith(EXTS)]
    files.sort(key=lambda n: EXTS.index(os.path.splitext(n)[1].lower()))
    for name in files:
        out.setdefault(key_of(name), rel(os.path.join(base, name)))
    return out


def main():
    heroes = scan("heroes")
    equipment = scan("equipment")
    sceneries = scan("sceneries")

    skins = {}
    for key, path in scan("skins").items():
        for hero in sorted(HERO_IDS, key=len, reverse=True):
            if key.startswith(hero + "-"):
                skins.setdefault(hero, {})[key[len(hero) + 1:]] = path
                break

    manifest = {
        "heroes": heroes,
        "skins": skins,
        "sceneries": sceneries,
        "equipment": equipment,
        "icons": scan("icons"),
    }
    os.makedirs(os.path.join(ROOT, "assets", "data"), exist_ok=True)
    with open(os.path.join(ROOT, "assets", "data", "art-manifest.json"), "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=1, sort_keys=True)
        fh.write("\n")

    data = {k: manifest[k] for k in ("heroes", "skins", "sceneries", "equipment")}
    with open(os.path.join(ROOT, "assets", "js", "art-data.js"), "w", encoding="utf-8") as fh:
        fh.write("/* Generated by tools/build-art-manifest.py — do not edit by hand.\n"
                 "   window.PDX_ART lists the art that ships in assets/. */\n")
        fh.write("window.PDX_ART = " + json.dumps(data, indent=0, sort_keys=True, ensure_ascii=False) + ";\n")

    print("heroes:      %d" % len(heroes))
    print("skins:       %d across %d heroes" % (sum(len(v) for v in skins.values()), len(skins)))
    print("sceneries:   %d" % len(sceneries))
    print("equipment:   %d" % len(equipment))
    print("wrote assets/data/art-manifest.json and assets/js/art-data.js")


if __name__ == "__main__":
    main()
